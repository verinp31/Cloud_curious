def as_records() -> list[dict[str, object]]:
    records = []
    for row in ROWS:
        rec = dict(zip(COLUMNS, row))
        rec["actif"] = "true" if rec["actif"] else "false"
        rec["priorite_rp"] = int(rec["priorite_rp"])
        records.append(rec)
    return records


def sql_literal(value: object) -> str:
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    text = str(value).replace("'", "''")
    return f"'{text}'"


def write_csv(path: Path, records: list[dict[str, object]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(records)


def write_json(path: Path, records: list[dict[str, object]]) -> None:
    typed = []
    for rec in records:
        item = dict(rec)
        item["actif"] = rec["actif"] == "true"
        typed.append(item)
    path.write_text(json.dumps(typed, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


