def md_escape(text: object) -> str:
    return str(text).replace("|", "\\|")


def write_catalog(path: Path, records: list[dict[str, object]]) -> None:
    by_country: dict[str, list[dict[str, object]]] = {}
    for rec in records:
        by_country.setdefault(str(rec["pays_nom"]), []).append(rec)

    order = ["France", "Belgique", "Suisse", "Portugal", "Espagne"]
    lines = [
        "# Catalogue médias — `ref_media`",
        "",
        "Liste opérationnelle pour relations presse. Les lignes **France** (`source_liste = EXEMPLE`) calent le format de la table. Les pays demandés sont en `source_liste = CIBLE`.",
        "",
        "Priorité RP : **1** incontournable · **2** important · **3** complémentaire.",
        "",
    ]
    for country in order:
        rows = by_country.get(country, [])
        if not rows:
            continue
        tag = "exemple de structure" if country == "France" else "liste cible"
        lines.append(f"## {country} ({len(rows)} médias — {tag})")
        lines.append("")
        lines.append("| id | Nom | Type | Thématique | Langue | Groupe | Priorité | URL |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for rec in rows:
            lines.append(
                "| {id} | {nom} | {typ} | {thm} | {lang} | {grp} | {prio} | {url} |".format(
                    id=rec["id_media"],
                    nom=md_escape(rec["nom"]),
                    typ=md_escape(rec["type_media"]),
                    thm=md_escape(rec["thematique"]),
                    lang=rec["langue"],
                    grp=md_escape(rec["groupe_media"]),
                    prio=rec["priorite_rp"],
                    url=rec["url"],
                )
            )
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    here = Path(__file__).resolve().parent
    records = as_records()
