def valider_grille(questions=None):
    questions = QUESTIONS if questions is None else questions
    ids = [q["id"] for q in questions]
    if ids != list(range(1, 101)):
        raise ValueError(f"Les identifiants doivent être 1..100 dans l'ordre, obtenu : {ids[:5]}…{ids[-3:]}")
    comptes = {code: 0 for code, _ in DOMAINES}
    for q in questions:
        if q["domaine"] not in comptes:
            raise ValueError(f"Domaine inconnu pour la question {q['id']} : {q['domaine']}")
        if q["levier"] not in LEVIERS:
            raise ValueError(f"Levier inconnu pour la question {q['id']} : {q['levier']}")
        if not q["titre"] or not q["pole0"] or not q["pole4"]:
            raise ValueError(f"Question {q['id']} incomplète")
        if q["pole0"] == q["pole4"]:
            raise ValueError(f"Question {q['id']} : les deux pôles sont identiques")
        comptes[q["domaine"]] += 1
    if comptes != EFFECTIFS:
        raise ValueError(f"Effectifs inattendus : {comptes}")
    return True


def par_domaine(questions=None):
    questions = QUESTIONS if questions is None else questions
    groupes = []
    for code, nom in DOMAINES:
        items = [q for q in questions if q["domaine"] == code]
        groupes.append({"code": code, "nom": nom, "questions": items})
    return groupes


def index_questions(questions=None):
    questions = QUESTIONS if questions is None else questions
    return {q["id"]: q for q in questions}


